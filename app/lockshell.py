#!/usr/bin/env python3
"""Build a private copy of Plasma's shell package used ONLY by the lock screen.

Plasma's lock screen draws its clock near the top of every screen, which is cut off on
a short bar screen. The lock screen wallpaper (org.kde.barscreenlock) draws its own
centred clock there, so this copy hides Plasma's clock on very wide screens only.

The whole package is re-copied from the installed one and lockscreen/LockScreenUi.qml
is re-patched from the installed version on every run (run at login by
bar-screen-dashboard.service). If a Plasma update changes the file so the patch no longer
applies, the original file is used unchanged: worst case two clocks, never a broken
lock screen.

ksmserver (which starts the lock screen) is pointed at this package with
PLASMA_DEFAULT_SHELL in ~/.config/systemd/user/plasma-ksmserver.service.d/bar-screen-lock.conf.
"""
import json
import os
import shutil

SYS = "/usr/share/plasma/shells/org.kde.plasma.desktop"
ID = "org.kde.plasma.barscreenlock"
DEST = os.path.expanduser("~/.local/share/plasma/shells/" + ID)
MARK = ".bar-screen-generated"
RATIO = float(os.environ.get("BAR_MIN_RATIO", "3") or 3)
WIDE = "(Window.width / Math.max(1, Window.height) < %g)" % RATIO
PATCHES = [
    ("            visible: y > 0 && config.alwaysShowClock\n",
     "            visible: y > 0 && config.alwaysShowClock && %s   // bar-screen-dashboard: hide on bar screens\n" % WIDE),
    ("            visible: !lockScreenUi.softwareRendering && config.alwaysShowClock\n",
     "            visible: !lockScreenUi.softwareRendering && config.alwaysShowClock && %s\n" % WIDE),
]


def build():
    if os.path.isdir(DEST):
        if not os.path.exists(os.path.join(DEST, MARK)):
            raise SystemExit("refusing to replace %s: not generated by this script" % DEST)
        shutil.rmtree(DEST)
    os.makedirs(os.path.join(DEST, "contents", "lockscreen"))
    open(os.path.join(DEST, MARK), "w").close()

    meta = json.load(open(os.path.join(SYS, "metadata.json")))
    meta["KPlugin"] = {"Id": ID, "Name": "Plasma desktop (lock screen with bar screen clock)",
                       "Version": meta["KPlugin"].get("Version", "")}
    json.dump(meta, open(os.path.join(DEST, "metadata.json"), "w"), indent=1)

    # Real copies: KPackage refuses symlinks that point outside the package.
    os.rmdir(os.path.join(DEST, "contents", "lockscreen"))
    shutil.copytree(os.path.join(SYS, "contents"), os.path.join(DEST, "contents"), dirs_exist_ok=True)
    lsys = os.path.join(SYS, "contents", "lockscreen")

    src = open(os.path.join(lsys, "LockScreenUi.qml")).read()
    out = src
    for a, b in PATCHES:
        if out.count(a) != 1:
            print("lockshell: patch anchor not found (Plasma changed?) - using the original file")
            out = None
            break
        out = out.replace(a, b)
    dst = os.path.join(DEST, "contents", "lockscreen", "LockScreenUi.qml")
    if out is not None:
        open(dst, "w").write(out)
        print("lockshell: patched LockScreenUi.qml")


DROPIN = os.path.expanduser("~/.config/systemd/user/plasma-ksmserver.service.d/bar-screen-lock.conf")

if __name__ == "__main__":
    import sys
    # The service runs this at every login with --if-enabled: only rebuild when the
    # lock screen clock was installed (./install.sh --lock-clock).
    if "--if-enabled" in sys.argv and not os.path.exists(DROPIN):
        raise SystemExit(0)
    build()
